const ROOT = get(ENV, "CS524_TABLES_ROOT", normpath(joinpath(@__DIR__, "..")))
using JSON, Statistics, Printf, Random, Plots

S = JSON.parsefile(joinpath(ROOT, "results", "injection_summary.json"))
const SG = Float64.(S["s_grid"]) .* 100           # percent
const NS = length(SG)
const ARMS = ["NOM", "BOX", "ELL"]
const KTOP = maximum(Float64.(S["kappa_grid"]))
res = S["results"]
patterns(sc) = sort(collect(keys(res[sc])))
nh(sc) = length(res[sc]["dense"][1])

# per-history beat indicators: strict test Sharpe above EW; a missing ELL book never beats
beat(o, a) = o[a] === nothing ? false : Float64(o[a]["sharpe"]) > Float64(o["EW"]["sharpe"])
beats(sc, p, a) = [[beat(o, a) for o in res[sc][p][j]] for j in 1:NS]           # NS vectors
gap(o, a, k) = o[a] === nothing ? nothing : Float64(o[a][k]) - Float64(o["EW"][k])

function wilson(k, n; z = 1.96)
    p = k / n; d = 1 + z^2 / n
    c = (p + z^2 / (2n)) / d; h = z * sqrt(p * (1 - p) / n + z^2 / (4n^2)) / d
    return c - h, c + h
end

# unweighted pool-adjacent-violators, nondecreasing
function isotonic(y)
    blocks = [[v] for v in y]
    i = 1
    while i < length(blocks)
        if mean(blocks[i]) > mean(blocks[i+1])
            blocks[i] = vcat(blocks[i], blocks[i+1]); deleteat!(blocks, i + 1)
            i = max(i - 1, 1)
        else
            i += 1
        end
    end
    return reduce(vcat, [fill(mean(b), length(b)) for b in blocks])
end

# strictly above 0.5. A pool of m grid points is a multiple of 1/(m n), m <= 9, so any real excess
# is at least 5.6e-4 (n = 200) or 6.2e-4 (n = 89); the 1e-12 margin only stops an exact tie that rounds to 0.5000000000000001
# from counting as above.
const ABOVE = 0.5 + 1e-12
# s* from p_beat over the grid: (index, value in percent, label)
function sstar(p)
    f = isotonic(p)
    f[1] > ABOVE && return (idx = 0, val = 0.0, label = "null already above 0.5", fit = f)
    k = findfirst(>(ABOVE), f)
    k === nothing && return (idx = 10, val = Inf, label = "not reached", fit = f)
    return (idx = k, val = SG[k], label = @sprintf("%.1f%%", SG[k]), fit = f)
end
pct(v, q) = sort(v)[clamp(ceil(Int, q * length(v)), 1, length(v))]   # inverse-cdf, safe with Inf

# s* bootstrap: one set of 1000 index vectors per scheme, primary then contiguous
Random.seed!(2030)
boot_idx = Dict(sc => [rand(1:nh(sc), nh(sc)) for _ in 1:1000] for sc in ("primary", "contiguous"))
function sstar_boot(sc, p, a)
    B = beats(sc, p, a)
    vals = [sstar([mean(B[j][ix]) for j in 1:NS]).val for ix in boot_idx[sc]]
    return pct(vals, 0.05), pct(vals, 0.95)
end

