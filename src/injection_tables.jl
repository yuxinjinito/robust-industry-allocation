ss = Dict{Tuple{String,String,String},Any}()
for sc in ("primary", "contiguous"), p in patterns(sc)
    pr("## p_beat against s: ", sc, ", ", p)
    pr()
    pr("| arm | ", join([@sprintf("%.1f%%", s) for s in SG], " | "), " | s* | s* 90% interval |")
    pr("|---|", repeat("---|", NS), "---|---|")
    fails = [count(o -> o["ell_failed"], res[sc][p][j]) for j in 1:NS]
    unrel = [f > 0.01 * nh(sc) for f in fails]
    for a in ARMS
        B = beats(sc, p, a)
        praw = [mean(b) for b in B]
        st = sstar(praw)
        lo, hi = sstar_boot(sc, p, a)
        ss[(sc, p, a)] = merge(st, (lo = lo, hi = hi, raw = praw))
        cells = [begin
                     k = count(B[j]); n = length(B[j]); w = wilson(k, n)
                     @sprintf("%.2f [%.2f, %.2f]", praw[j], w[1], w[2]) * ((a == "ELL" && unrel[j]) ? " UNRELIABLE" : "")
                 end for j in 1:NS]
        pr("| ", a, " | ", join(cells, " | "), " | ", st.label, " | ", @sprintf("%s to %s", lo, hi), " |")
    end
    pr()
    pr("Median paired Sharpe gap to EW and median paired maxDD gap (percentage points), by s:")
    pr()
    for a in ARMS
        g = [begin
                 v = filter(!isnothing, [gap(o, a, "sharpe") for o in res[sc][p][j]])
                 d = filter(!isnothing, [gap(o, a, "maxdd") for o in res[sc][p][j]])
                 @sprintf("%.3f / %.1f", median(v), median(d))
             end for j in 1:NS]
        pr("- ", a, ": ", join(g, ", "))
    end
    pr()
    pr("Fraction of histories with a smaller test maxDD than EW [Wilson 95%], by s:")
    pr()
    for a in ARMS
        g = [begin
                 bd = [o[a] !== nothing && Float64(o[a]["maxdd"]) < Float64(o["EW"]["maxdd"]) for o in res[sc][p][j]]
                 w = wilson(count(bd), length(bd))
                 @sprintf("%.2f [%.2f, %.2f]", mean(bd), w[1], w[2])
             end for j in 1:NS]
        pr("- ", a, ": ", join(g, ", "))
    end
    ktop = [count(o -> Float64(o["h"]["ELL"]) == KTOP, res[sc][p][j]) / nh(sc) for j in 1:NS]
    k0 = [count(o -> Float64(o["h"]["ELL"]) == 0.0, res[sc][p][j]) / nh(sc) for j in 1:NS]
    g0 = [count(o -> o["h"]["BOX"] == 0, res[sc][p][j]) / nh(sc) for j in 1:NS]
    pr("- ELL κ* at the top of GRID_K, by s: ", join([@sprintf("%.2f", v) for v in ktop], ", "))
    pr("- ELL κ* = 0, by s: ", join([@sprintf("%.2f", v) for v in k0], ", "))
    pr("- BOX Γ* = 0, by s: ", join([@sprintf("%.2f", v) for v in g0], ", "))
    pr("- histories with a failed ELL solve, by s: ", join(fails, ", "),
       any(f -> f > 0.01 * nh(sc), fails) ? " (UNRELIABLE cells present)" : "")
    pr()
end

