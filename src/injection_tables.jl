p2 = String[]; p2v = :held
for a in ("BOX", "ELL")
    global p2v    # a top-level loop in a script would otherwise make a new local
    st = ss[("primary", "dense", a)]
    if st.idx == 0
        push!(p2, "$a undecidable (null already above 0.5)"); p2v == :held && (p2v = :undecidable)
    else
        okk = st.val >= 3; okk || (p2v = :refuted)
        push!(p2, "$a s* = $(st.label)")
    end
end
push!(R_, "P2 " * (p2v == :held ? "held" : p2v == :refuted ? "REFUTED" : "undecidable") * ": " * join(p2, "; ") * ".")
f10 = [ss[("primary", "dense", a)].fit[end] for a in ("BOX", "ELL")]
push!(R_, @sprintf("P3 %s: isotonic p_beat at 10%%: BOX %.3f, ELL %.3f.", all(>(ABOVE), f10) ? "held" : "REFUTED", f10...))
function p4_verdict(a, L, U)
    st = ss[("primary", "dense", a)]
    (st.idx == 0 || st.idx == 10) && return "undecidable ($(st.label))"
    st.lo > 100U && return "held"
    st.hi <= 100L && return "refuted"
    return "inconclusive"
end
v1 = Dict(a => p4_verdict(a, RD["L"], RD["U"]) for a in ("BOX", "ELL"))
v2 = Dict(a => p4_verdict(a, RD["L_blk"], RD["U_blk"]) for a in ("BOX", "ELL"))
agg(v) = all(==("held"), values(v)) ? "held" : any(==("refuted"), values(v)) ? "REFUTED" : "per arm"
p4 = agg(v1)
note = (v1 == v2) ? "" : " The block version gives BOX $(v2["BOX"]), ELL $(v2["ELL"]): P4 depends on the independence assumption."
push!(R_, @sprintf("P4 %s: BOX %s (s* %s, interval %s to %s), ELL %s (s* %s, interval %s to %s), against [L, U] = [%.2f, %.2f].",
                   p4, v1["BOX"], ss[("primary", "dense", "BOX")].label, ss[("primary", "dense", "BOX")].lo, ss[("primary", "dense", "BOX")].hi,
                   v1["ELL"], ss[("primary", "dense", "ELL")].label, ss[("primary", "dense", "ELL")].lo, ss[("primary", "dense", "ELL")].hi,
                   100RD["L"], 100RD["U"]) * note)
function interp(fit, s)
    s > SG[end] && return nothing
    k = findlast(<=(s), SG)
    k == NS && return fit[NS]
    return fit[k] + (fit[k+1] - fit[k]) * (s - SG[k]) / (SG[k+1] - SG[k])
end
sh = 100RD["s_hat"]
c5 = [interp(ss[("contiguous", "dense", a)].fit, sh) for a in ("BOX", "ELL")]
if any(isnothing, c5)
    push!(R_, "P5 undecidable: s_hat above 10%.")
else
    t = [10 / 31, 11 / 31]
    okk = all(abs.(c5 .- t) .<= 0.15)
    push!(R_, @sprintf("P5 %s: contiguous isotonic p_beat at s_hat = %.2f%%: BOX %.3f (target 0.323), ELL %.3f (target 0.355). At s = 0: BOX %.3f, ELL %.3f.",
                       okk ? "held" : "REFUTED", sh, c5..., ss[("contiguous", "dense", "BOX")].raw[1], ss[("contiguous", "dense", "ELL")].raw[1]))
end
p6 = String[]; p6v = :held
for a in ("BOX", "ELL")
    global p6v
    i1, i2 = ss[("primary", "dense", a)].idx, ss[("contiguous", "dense", a)].idx
    if i1 == 0 || i2 == 0
        p6v == :held && (p6v = :undecidable); push!(p6, "$a undecidable")
    else
        abs(i1 - i2) <= 1 || (p6v = :refuted); push!(p6, "$a primary index $i1, contiguous $i2")
    end
end
push!(R_, "P6 " * (p6v == :held ? "held" : p6v == :refuted ? "REFUTED" : "undecidable") * ": " * join(p6, "; ") * ".")
is_, id_ = ss[("primary", "sparse", "NOM")].idx, ss[("primary", "dense", "NOM")].idx
p7 = (is_ == 0 || id_ == 0) ? "undecidable" : is_ < id_ ? "held" : "REFUTED"
push!(R_, "P7 $(p7): NOM s* sparse $(ss[("primary", "sparse", "NOM")].label), dense $(ss[("primary", "dense", "NOM")].label).")
