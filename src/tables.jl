# summary.json -> results/tables.md and results/fig_sharpe_vs_ew.png.
# Every number here is computed from summary.json alone. julia --project=. src/tables.jl

const ROOT = get(ENV, "CS524_TABLES_ROOT", normpath(joinpath(@__DIR__, "..")))
using JSON, Statistics, Printf, Plots

S = JSON.parsefile(joinpath(ROOT, "results", "summary.json"))
const ARMS = ["NOM", "EW", "BOX", "ELL", "RBOX", "RELL", "DRIFT"]
const OPT = ["NOM", "BOX", "ELL", "RBOX", "RELL", "DRIFT"]   # the six non-EW arms
W = S["windows"]
@assert length(W) == 31

v(arm, key) = [Float64(w["arms"][arm]["score"][key]) for w in W]
hyp(arm) = [w["arms"][arm]["h"] for w in W]

# one-sided exact sign test, P(Bin(n, 1/2) >= k)
signp(k, n) = n == 0 ? 1.0 : Float64(sum(binomial(big(n), i) for i in k:n) / big(2)^n)
function holm(ps)
    m = length(ps); o = sortperm(ps); adj = zeros(m); run = 0.0
    for (r, i) in enumerate(o)
        run = max(run, min(1.0, (m - r + 1) * ps[i])); adj[i] = run
    end
    return adj
end

# ---- primary comparison: each rule against equal weight on Sharpe over 31 windows
sh_ew, dd_ew = v("EW", "sharpe"), v("EW", "maxdd")
prim = Dict{String,Any}()
for a in OPT
    same = [w["arms"][a]["same_as_EW"] for w in W]
    beat = v(a, "sharpe") .> sh_ew
    n = count(.!same); k = count(beat .& .!same)
    prim[a] = (count = count(beat), n = n, k = k, p = signp(k, n), dd = count(v(a, "maxdd") .< dd_ew))
end
padj = holm([prim[a].p for a in OPT])
holm_of = Dict(OPT[i] => padj[i] for i in eachindex(OPT))

io = IOBuffer()
pr(args...) = println(io, args...)
fmt(x; d = 3) = x === nothing ? "-" : (x isa Number ? string(round(x, digits = d)) : string(x))

h = S["header"]
pr("# Extension results")
pr()
pr("Generated by `src/tables.jl` from `results/summary.json` (code ", h["code_commit"][1:7],
   ", run ", h["run_date"], "). Clarabel ALMOST_OPTIMAL solves: ",
   length(S["almost_optimal"]), ".")
pr()
pr("## T1. Which stance does best against equal weight, over 31 windows?")
pr()
pr("| arm | median Sharpe | median Sharpe net 10 bps | median maxDD % | median annual turnover | Sharpe > EW (of 31) | n, Holm p | maxDD < EW (of 31) |")
pr("|---|---|---|---|---|---|---|---|")
for a in ARMS
    note = a in ("RBOX", "RELL") ? " (two validation looks)" : ""
    sg = a == "EW" ? ("-", "-", "-") :
         (string(prim[a].count), @sprintf("%d, %.3g", prim[a].n, holm_of[a]), string(prim[a].dd))
    pr("| ", a, note, " | ", fmt(median(v(a, "sharpe"))), " | ", fmt(median(v(a, "sharpe_net_10bps"))),
       " | ", fmt(median(v(a, "maxdd")); d = 1), " | ", fmt(median(v(a, "turnover_annual")); d = 2),
       " | ", sg[1], " | ", sg[2], " | ", sg[3], " |")
end
pr()
pr("Sign tests count windows whose test Sharpe exceeds EW's among the n windows where the book differs from EW's; ",
   "fit blocks overlap, so these are checks on counts, not significance claims about the method.")
pr()

pr("## T2. The single 2023-2025 holdout")
pr()
Hd = S["holdout"]
hs(a, k) = Float64(Hd["arms"][a]["score"][k])
pr("| arm | hyperparameter | Sharpe | Sharpe net 10 bps | maxDD % | annual turnover | Sharpe minus EW | maxDD minus EW |")
pr("|---|---|---|---|---|---|---|---|")
for a in ARMS
    pr("| ", a, " | ", fmt(Hd["arms"][a]["h"]), " | ", fmt(hs(a, "sharpe"); d = 4), " | ", fmt(hs(a, "sharpe_net_10bps"); d = 4),
       " | ", fmt(hs(a, "maxdd"); d = 2), " | ", fmt(hs(a, "turnover_annual"); d = 2), " | ",
       fmt(hs(a, "sharpe") - hs("EW", "sharpe"); d = 4), " | ", fmt(hs(a, "maxdd") - hs("EW", "maxdd"); d = 2), " |")
end
pr()

pr("## T3. How much do costs and rebalancing frequency move the median Sharpe?")
pr()
ckeys = ["sharpe", "sharpe_net_5bps", "sharpe_net_10bps", "sharpe_net_20bps", "sharpe_net_50bps", "sharpe_net_10bps_monthly"]
pr("| arm | gross | 5 bps | 10 bps | 20 bps | 50 bps | 10 bps monthly |")
pr("|---|---|---|---|---|---|---|")
for a in ARMS
    pr("| ", a, " | ", join([fmt(median(v(a, k))) for k in ckeys], " | "), " |")
end
pr()

pr("## T4. Per-window diagnostics")
pr()
pr("| test window | Γ* BOX | Γ* DRIFT | κ* | w* RBOX | w* RELL | w_J | mbar sign | drift ratio | drift excess | holdings NOM/BOX/ELL/RBOX/RELL/DRIFT |")
pr("|---|---|---|---|---|---|---|---|---|---|---|")
for w in W
    t = w["train"]
    hold = join([w["arms"][a]["score"]["holdings"] for a in OPT], "/")
    pr("| ", w["label"], " | ", w["arms"]["BOX"]["h"], " | ", w["arms"]["DRIFT"]["h"], " | ", fmt(w["arms"]["ELL"]["h"]),
       " | ", fmt(w["arms"]["RBOX"]["h"]), " | ", fmt(w["arms"]["RELL"]["h"]), " | ", fmt(t["wJ"]),
       " | ", Int(t["mbar_sign"]), " | ", fmt(t["drift_ratio"]), " | ", fmt(t["drift_excess"]), " | ", hold, " |")
end
pr()
kmax = maximum(Float64.(S["grids"]["kappa"]))
edge(a, val) = count(w -> w["arms"][a]["h"] !== nothing && Float64(w["arms"][a]["h"]) == val, W)
pr("Selections at a grid edge, out of 31 (descriptive; at the top edge the selected value is not an interior optimum): ",
   "κ* = ", kmax, " in ", edge("ELL", kmax), "; Γ* = 30 in BOX ", edge("BOX", 30.0), ", DRIFT ", edge("DRIFT", 30.0),
   "; w* = 1 in RBOX ", edge("RBOX", 1.0), ", RELL ", edge("RELL", 1.0),
   "; at the bottom edge κ* = 0 in ", edge("ELL", 0.0), ", Γ* = 0 in BOX ", edge("BOX", 0.0), ", DRIFT ", edge("DRIFT", 0.0), ".")
pr()

# ---- predictions stated before the run, each decided by the number printed next to it
pr("## Predictions")
pr()
res = String[]
cnt = Dict(a => prim[a].count for a in OPT)
p1 = maximum(values(cnt)) <= 20
push!(res, @sprintf("P1 %s: the largest Sharpe > EW count is %d (%s); refuted at 21.", p1 ? "held" : "REFUTED",
                    maximum(values(cnt)), join([a for a in OPT if cnt[a] == maximum(values(cnt))], ", ")))
p2 = all(cnt[a] <= cnt["ELL"] for a in OPT)
push!(res, @sprintf("P2 %s: ELL's count is %d; the counts are %s.", p2 ? "held" : "REFUTED", cnt["ELL"],
                    join(["$a $(cnt[a])" for a in OPT], ", ")))
p3a, p3b = prim["ELL"].dd >= 16, prim["ELL"].dd > prim["BOX"].dd
push!(res, @sprintf("P3 %s: ELL has the smaller maxDD than EW in %d of 31 (needs 16), BOX in %d.",
                    (p3a && p3b) ? "held" : "REFUTED", prim["ELL"].dd, prim["BOX"].dd))
mh_ell, mh_box = median(v("ELL", "holdings")), median(v("BOX", "holdings"))
nz_ell = count(w -> w["arms"]["ELL"]["score"]["has_weight_1e-5_to_1e-3"], W)
nz_rell = count(w -> w["arms"]["RELL"]["score"]["has_weight_1e-5_to_1e-3"], W)
push!(res, @sprintf("P4 %s: median holdings ELL %.1f, BOX %.1f. ELL books with a weight in [1e-5, 1e-3]: %d of 31 (RELL: %d).",
                    mh_ell < mh_box ? "held" : "REFUTED", mh_ell, mh_box, nz_ell, nz_rell))
drops = Dict(a => median(v(a, "sharpe") .- v(a, "sharpe_net_10bps")) for a in ARMS)
p5a = all(drops[a] < 0.05 for a in ARMS)
mg = Dict(a => median(v(a, "sharpe")) for a in ARMS); mn = Dict(a => median(v(a, "sharpe_net_10bps")) for a in ARMS)
flips = [(i, j) for i in ARMS for j in ARMS if mg[i] - mg[j] > 0.001 && mn[j] - mn[i] > 0.001]
push!(res, @sprintf("P5 %s: largest median paired drop at 10 bps is %.4f (%s); order flips: %s.",
                    (p5a && isempty(flips)) ? "held" : "REFUTED", maximum(values(drops)),
                    ARMS[argmax([drops[a] for a in ARMS])], isempty(flips) ? "none" : join(["$i/$j" for (i, j) in flips], ", ")))
p6 = String[]; p6ok = true
for (a, b) in (("RBOX", "BOX"), ("RELL", "ELL"))
    npos = count(>(0), Float64.(hyp(a)))
    md = median(v(a, "sharpe") .- v(b, "sharpe"))
    global p6ok &= npos >= 16 && -0.05 <= md <= 0.05
    push!(p6, @sprintf("%s w* > 0 in %d of 31, median paired Sharpe minus %s %.4f", a, npos, b, md))
end
push!(res, "P6 " * (p6ok ? "held" : "REFUTED") * ": " * join(p6, "; ") * ".")
ex = [Float64(w["train"]["drift_excess"]) for w in W]
ndiff = count(w -> w["arms"]["DRIFT"]["h"] != w["arms"]["BOX"]["h"], W)
push!(res, @sprintf("P7 %s: drift excess > 1.1 in %d of 31 (needs 16), median excess %.3f; DRIFT Γ* differs from BOX in %d (needs 10).",
                    (count(>(1.1), ex) >= 16 && ndiff >= 10) ? "held" : "REFUTED", count(>(1.1), ex), median(ex), ndiff))
foreach(r -> pr("- ", r), res)
pr()
pr("Kappa = 0 ELL versus NOM, largest weight difference over windows: ",
   @sprintf("%.3g", maximum(Float64(w["ell_kappa0_vs_nom_max_diff"]) for w in W)), ".")

pr()
pr("## T5. Return and risk of all-in, equal weight and the robust books")
pr()
pr("Descriptive. Rolling: median over the 31 windows, middle half in brackets. Holdout: 2023-2025.")
pr()
qq(x) = @sprintf("%.1f [%.1f, %.1f]", median(x), quantile(x, 0.25), quantile(x, 0.75))
qs(x) = @sprintf("%.2f [%.2f, %.2f]", median(x), quantile(x, 0.25), quantile(x, 0.75))
pr("| book | ann. return % | ann. vol % | Sharpe | max drawdown % | holdout return / vol / Sharpe / maxDD |")
pr("|---|---|---|---|---|---|")
for (a, lab) in (("NOM", "all-in (NOM, Γ = 0)"), ("EW", "equal weight"), ("BOX", "robust, box (report)"), ("ELL", "robust, ellipsoid"))
    pr("| ", lab, " | ", qq(v(a, "ann_ret")), " | ", qq(v(a, "ann_vol")), " | ", qs(v(a, "sharpe")), " | ", qq(v(a, "maxdd")), " | ",
       @sprintf("%.2f / %.2f / %.2f / %.2f", hs(a, "ann_ret"), hs(a, "ann_vol"), hs(a, "sharpe"), hs(a, "maxdd")), " |")
end

open(joinpath(ROOT, "results", "tables.md"), "w") do f
    write(f, String(take!(io)))
end

