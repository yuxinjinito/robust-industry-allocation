gr()
plt = plot(size = (820, 460), legend = false, left_margin = 5Plots.mm, bottom_margin = 5Plots.mm,
           xticks = (1:length(OPT), OPT), xlabel = "Arm", ylabel = "Test Sharpe minus equal-weight Sharpe",
           title = "Per-window test Sharpe minus equal weight, 31 rolling windows")
hline!(plt, [0.0], color = :gray, linestyle = :dash)
for (i, a) in enumerate(OPT)
    y = v(a, "sharpe") .- sh_ew
    x = i .+ 0.25 .* ((1:length(y)) ./ length(y) .- 0.5)
    scatter!(plt, x, y, markersize = 4, markerstrokewidth = 0)
end
savefig(plt, joinpath(ROOT, "results", "fig_sharpe_vs_ew.png"))
